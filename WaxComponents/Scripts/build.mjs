/* Build step for the library's browser scripts (invoked by 'npm run build:js' /
 * 'build:js:min'; the MSBuild BuildScripts target picks the variant per Configuration).
 *
 * - Scripts/theme.ts -> wwwroot/js/theme.js
 *   ES module imported by ThemeService (./_content/WaxComponents/js/theme.js).
 * - Scripts/themePreloader.ts -> Services/Theme/ThemePreloaderScript.generated.cs
 *   IIFE compiled into a C# raw-string const that ThemePreloader.razor inlines in
 *   <head>. It cannot ship as a static file: an extra request before first paint
 *   would reintroduce the theme flash the preloader exists to prevent.
 *
 * Usage: node Scripts/build.mjs debug|release  (release minifies)
 */
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const minify = process.argv[2] === "release";

const [theme, preloader] = await Promise.all([
    build({
        entryPoints: ["Scripts/theme.ts"],
        format: "esm",
        target: ["es2020"],
        minify,
        write: false,
    }),
    build({
        entryPoints: ["Scripts/themePreloader.ts"],
        format: "iife",
        target: ["es2020"],
        minify,
        write: false,
    }),
]);

await writeFile("wwwroot/js/theme.js", theme.outputFiles[0].text);

// "</script" inside the inlined script would close the <script> tag early.
const js = preloader.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");

await writeFile("Services/Theme/ThemePreloaderScript.generated.cs", `// <auto-generated />
// Inlined by ThemePreloader.razor. Compiled from Scripts/themePreloader.ts by esbuild
// (npm run build:js / build:js:min). Do not edit.
namespace WaxComponents.Services.Theme;

internal static class ThemePreloaderScript
{
    internal const string Script = """
${js}
""";
}
`);
